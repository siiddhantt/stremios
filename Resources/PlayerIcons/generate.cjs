#!/usr/bin/env node
// Development-only rasterization. The app embeds the resulting PNG bytes;
// it does not load Node, Sharp, SVG, fonts, or network resources at runtime.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const sharp = require('sharp');
const root = __dirname;
const commit = 'a4ce1404bc6d24d3c365afe7b258d6bf6f48d62d';
const entries = [
  ['close','chevron-down'], ['view','aspect-ratio'], ['audio','volume'],
  ['cc','badge-cc'], ['fullscreen','maximize'], ['fullscreen-exit','minimize'],
  ['play','player-play'], ['pause','player-pause'],
  ['back','rewind-backward-15'], ['forward','rewind-forward-15']
];
const sha = data => crypto.createHash('sha256').update(data).digest('hex');
(async () => {
  const records = [];
  const parts = ['/* Generated by generate.cjs from official Tabler paths; do not hand-edit. */',
    '/* MIT: Copyright (c) 2020-2026 Paweł Kuna. See LICENSE.txt and ThirdPartyNotices.txt. */',
    '#include <stddef.h>',
    'typedef struct { const char *name; const unsigned char *bytes[3]; size_t lengths[3]; } MSPlayerIconAsset;'];
  const table = [];
  for (const [name, upstream] of entries) {
    const input = fs.readFileSync(path.join(root,upstream+'.svg'));
    // Only substitute the inherited color. Geometry and default two-unit
    // round-cap/round-join strokes are kept exactly as published upstream.
    const svg = Buffer.from(input.toString().replaceAll('currentColor','#ffffff'));
    const pngs = [];
    const symbols = [];
    for (const scale of [1,2,3]) {
      const filename = name + (scale === 1 ? '' : '@'+scale+'x') + '.png';
      const png = await sharp(svg, {density:72*scale}).resize(24*scale,24*scale).png({compressionLevel:9,adaptiveFiltering:false}).toBuffer();
      fs.writeFileSync(path.join(root,filename),png);
      const symbol = 'MSPlayerPNG_'+name.replaceAll('-','_')+'_'+scale;
      const rows=[]; for(let i=0;i<png.length;i+=16)rows.push('    '+[...png.subarray(i,i+16)].map(x=>'0x'+x.toString(16).padStart(2,'0')).join(',')+',');
      parts.push('static const unsigned char '+symbol+'[] = {\n'+rows.join('\n')+'\n};');
      symbols.push(symbol); pngs.push({filename,scale,width:24*scale,height:24*scale,bytes:png.length,sha256:sha(png)});
    }
    table.push('    {"'+name+'", {'+symbols.join(', ')+'}, {'+symbols.map(x=>'sizeof('+x+')').join(', ')+'}}');
    records.push({name,upstream,sourceURL:'https://raw.githubusercontent.com/tabler/tabler-icons/'+commit+'/icons/outline/'+upstream+'.svg',svgSHA256:sha(input),pngs});
  }
  parts.push('static const MSPlayerIconAsset MSPlayerIconAssets[] = {\n'+table.join(',\n')+'\n};');
  parts.push('static const size_t MSPlayerIconAssetCount = sizeof(MSPlayerIconAssets) / sizeof(MSPlayerIconAssets[0]);');
  fs.writeFileSync(path.join(root,'GeneratedIcons.h'),parts.join('\n')+'\n');
  const manifest = {schemaVersion:1,library:'Tabler Icons',commit,license:'MIT',licenseURL:'https://github.com/tabler/tabler-icons/blob/'+commit+'/LICENSE',licenseSHA256:sha(fs.readFileSync(path.join(root,'LICENSE.txt'))),pointSize:24,strokeWidth:2,modifications:'CurrentColor set to white for UIImage template rendering; paths, stroke width, caps and joins unchanged.',renderer:{sharp:sharp.versions.sharp,rsvg:sharp.versions.rsvg,vips:sharp.versions.vips},totalRasterBytes:records.flatMap(x=>x.pngs).reduce((s,x)=>s+x.bytes,0),icons:records};
  fs.writeFileSync(path.join(root,'manifest.json'),JSON.stringify(manifest,null,2)+'\n');
  console.log(JSON.stringify({icons:records.length,rasterBytes:manifest.totalRasterBytes,headerBytes:fs.statSync(path.join(root,'GeneratedIcons.h')).size}));
})().catch(error=>{console.error(error);process.exit(1);});
